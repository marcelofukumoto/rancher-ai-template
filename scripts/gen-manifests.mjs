#!/usr/bin/env node
/* eslint-disable no-console */
// Regenerate pkg/ai-templating/install/manifests.ts from the YAML sources, so the extension can
// embed and auto-install its cluster dependencies (see pkg/ai-templating/install/ensure.ts).
//
//   node scripts/gen-manifests.mjs
//
// Sources:
//   pkg/ai-templating/crd/templating.rancher.io.crds.yaml   -> CRDS
//   pkg/ai-templating/agents/*.aiagentconfig.yaml           -> AGENT_CRS
//   pkg/ai-templating/examples/sample-crs.yaml (Config+Home) -> SEED_CRS
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import yaml from 'js-yaml';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = path.join(root, 'pkg/ai-templating');

const loadAll = (p) => yaml.loadAll(fs.readFileSync(p, 'utf8')).filter(Boolean);
const load = (p) => yaml.load(fs.readFileSync(p, 'utf8'));

const crds = loadAll(path.join(base, 'crd/templating.rancher.io.crds.yaml'));
const sample = loadAll(path.join(base, 'examples/sample-crs.yaml'));
const agents = fs.readdirSync(path.join(base, 'agents'))
  .filter((f) => f.endsWith('.yaml'))
  .map((f) => load(path.join(base, 'agents', f)));

// Seed only the config + a HomeTemplate so a fresh install shows a working custom Home.
const seed = sample.filter((d) => d.kind === 'TemplatingConfig' || d.kind === 'HomeTemplate');

const out = `/* eslint-disable */
// AUTO-GENERATED by scripts/gen-manifests.mjs — do not edit by hand.
// Embedded manifests the extension ensures on install (see install/ensure.ts).

export const CRDS: any[] = ${ JSON.stringify(crds, null, 2) };

export const AGENT_CRS: any[] = ${ JSON.stringify(agents, null, 2) };

export const SEED_CRS: any[] = ${ JSON.stringify(seed, null, 2) };
`;

fs.writeFileSync(path.join(base, 'install/manifests.ts'), out);
console.log('wrote install/manifests.ts', { crds: crds.length, agents: agents.length, seed: seed.length });
